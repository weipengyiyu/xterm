'use strict';
const assert = require('assert');
const { EventEmitter } = require('events');
const { installTerminalWindowFocus } = require('../desktop/terminal-focus');
const win = new EventEmitter();
const contents = win.webContents = new EventEmitter();
let focused = true, contentFocus = false, minimized = false, loading = false;
let focusCalls = 0, notifications = 0, reloads = 0;
win.isDestroyed = contents.isDestroyed = () => false;
win.isFocused = () => focused;
win.isMinimized = () => minimized;
contents.isFocused = () => contentFocus;
contents.isLoadingMainFrame = () => loading;
contents.focus = () => { focusCalls++; contentFocus = true; };
contents.send = channel => { assert.strictEqual(channel, 'xterm-terminal-focus'); notifications++; };
contents.reloadIgnoringCache = () => reloads++;
installTerminalWindowFocus(win);
win.emit('focus');
assert.strictEqual(focusCalls, 1);
assert.strictEqual(notifications, 1);
focused = false; contentFocus = false;
win.emit('focus');
assert.strictEqual(focusCalls, 1, 'must not steal focus from another application');
focused = true; minimized = true;
win.emit('restore');
assert.strictEqual(focusCalls, 1);
minimized = false; loading = true;
win.emit('restore');
assert.strictEqual(focusCalls, 2);
assert.strictEqual(notifications, 1, 'do not notify a loading document');
loading = false;
contents.emit('did-finish-load');
assert.strictEqual(notifications, 2);
contentFocus = false;
let prevented = 0;
const event = { preventDefault: () => prevented++ };
contents.emit('before-input-event', event, { type: 'keyDown', key: ' ' });
assert.strictEqual(focusCalls, 3, 'restore native webContents focus before the key reaches Chromium');
contents.emit('before-input-event', event, { type: 'keyDown', key: 'R', control: true, shift: true });
assert.strictEqual(reloads, 1);
assert.strictEqual(prevented, 1);
contents.emit('before-input-event', event, { type: 'keyDown', key: 'r', control: true });
contents.emit('before-input-event', event, { type: 'keyUp', key: 'R', control: true, shift: true });
assert.strictEqual(reloads, 1, 'preserve the shell/reconnect Ctrl+R shortcut');
contents.emit('before-input-event', event, { type: 'keyDown', key: 'F5', control: true });
assert.strictEqual(reloads, 2, 'the documented Ctrl+F5 shortcut must also work without a menu');
win.emit('closed');
assert.strictEqual(win.listenerCount('focus'), 0);
assert.strictEqual(contents.listenerCount('before-input-event'), 0);
console.log('✓ Desktop focus: native routing, background protection, menu-free reload and cleanup passed');
